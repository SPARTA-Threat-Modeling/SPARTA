package be.kuleuven.cs.distrinet.sparta.analysis.vql;

import org.eclipse.jface.text.IDocument;
import org.eclipse.jface.text.presentation.IPresentationReconciler;
import org.eclipse.jface.text.presentation.PresentationReconciler;
import org.eclipse.jface.text.rules.DefaultDamagerRepairer;
import org.eclipse.jface.text.source.ISourceViewer;
import org.eclipse.jface.text.source.SourceViewerConfiguration;

/**
 * Wires the {@link VqlTokenScanner} into a {@link org.eclipse.jface.text.source.SourceViewer}
 * so that VQL text is syntax-colored. A single default partition is used (the scanner is
 * purely lexical), which is sufficient for highlight-only editing.
 */
public class VqlSourceViewerConfiguration extends SourceViewerConfiguration {

	private final VqlColorManager colorManager;

	public VqlSourceViewerConfiguration(VqlColorManager colorManager) {
		this.colorManager = colorManager;
	}

	@Override
	public IPresentationReconciler getPresentationReconciler(ISourceViewer sourceViewer) {
		PresentationReconciler reconciler = new PresentationReconciler();
		DefaultDamagerRepairer dr = new DefaultDamagerRepairer(new VqlTokenScanner(colorManager));
		reconciler.setDamager(dr, IDocument.DEFAULT_CONTENT_TYPE);
		reconciler.setRepairer(dr, IDocument.DEFAULT_CONTENT_TYPE);
		return reconciler;
	}
}
